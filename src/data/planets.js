export const ORBIT_SCALE = 40;

export function getPlanetByKey(key) {
  const lower = key.toLowerCase();
  return PLANETS.find(p =>
    p.name.toLowerCase() === lower ||
    p.nameCn === key ||
    p.distance.toString() === key
  );
}
